"""
Plot mileage vs price for car data generated by extracting_car_data_v3claude.py.

Usage:
    python analyzing_car_data_v3claude.py                 # uses the most recent cardata_anwb_*.xlsx
    python analyzing_car_data_v3claude.py <file.xlsx>     # uses a specific file

The plot (PDF + PNG) is saved in OUTPUTDIR/plots_<current year>/ (e.g. .../auto/plots_2026/),
named after the Excel file + '_mileage-vs-price'.
"""

import datetime
import glob
import os
import sys

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sn
from scipy.optimize import curve_fit

OUTPUTDIR = '/Users/m.wehrens/Documents/Personal/auto/'
cm_to_inch = 1 / 2.54

########################################################################
# Load data

if len(sys.argv) > 1 and sys.argv[1].endswith('.xlsx'):
    data_path = sys.argv[1]
else:
    # most recently created file from extracting_car_data_v3claude.py
    data_path = max(glob.glob(os.path.join(OUTPUTDIR, '*', 'cardata_anwb_*.xlsx')), key=os.path.getmtime)
print(f'Loading {data_path}')

df = pd.read_excel(data_path, sheet_name='Sheet1')
df = df.dropna(subset=['mileage_km', 'price'])
car_name = f"{df['brand'].iloc[0]} {df['model_name'].iloc[0]}"

########################################################################
# Linear fit: price = slope * mileage + intercept

slope, intercept = np.polyfit(df['mileage_km'], df['price'], 1)
loss_per_10000km = -slope * 10000
print(f'Fit: price = {intercept:.0f} + {slope:.4f} * km  '
      f'(≈ €{loss_per_10000km:.0f} less per 10.000 km, n={len(df)})')

########################################################################
# Plot

plt.rcParams.update({'font.size': 8})
fig, ax = plt.subplots(1, 1, figsize=(13 * cm_to_inch, 8 * cm_to_inch))

sn.regplot(data=df, x='mileage_km', y='price', ax=ax, ci=None,
           scatter_kws=dict(s=18, color='#0072B2', alpha=0.7, edgecolor='white', linewidths=0.5),
           line_kws=dict(color='black', linewidth=2))

ax.set_title(f'{car_name}: kilometerstand vs prijs (n={len(df)})\n'
             f'fit: −€{loss_per_10000km:,.0f} per 10.000 km'.replace(',', '.'))
ax.set_xlabel('Kilometerstand (km)')
ax.set_ylabel('Prijs (€)')
ax.xaxis.set_major_formatter(plt.FuncFormatter(lambda x, _: f'{x:,.0f}'.replace(',', '.')))
ax.yaxis.set_major_formatter(plt.FuncFormatter(lambda y, _: f'{y:,.0f}'.replace(',', '.')))
ax.set_xlim(left=0)
ax.grid(color='#dddddd', linewidth=0.5)
ax.set_axisbelow(True)
sn.despine(ax=ax)
plt.tight_layout()

plot_dir = os.path.join(OUTPUTDIR, f'plots_{datetime.date.today().year}')
os.makedirs(plot_dir, exist_ok=True)
out_base = os.path.join(plot_dir, os.path.basename(data_path).replace('.xlsx', '_mileage-vs-price'))
fig.savefig(out_base + '.pdf', dpi=300, bbox_inches='tight')
fig.savefig(out_base + '.png', dpi=300, bbox_inches='tight')
print(f'Saved plot to {out_base}.pdf / .png')
plt.show()


########################################################################
# Plot 2 (as in the v2 script, extended): linear and exponential depreciation fits
#   row 1: price vs mileage  (points colored by age)
#   row 2: price vs age      (points colored by mileage)
# Fits use only cars above a minimum mileage/age, since nearly-new cars are priced differently.

MIN_KM = 15000     # row 1: fit cars with more than this mileage
MIN_AGE = 1.0      # row 2: fit cars older than this (years)

# age in years, from first registration date (fallback: construction year)
today = pd.Timestamp(datetime.date.today())
first_reg = pd.to_datetime(df['first_registration'], errors='coerce')
df['age_years'] = ((today - first_reg).dt.days / 365.25).fillna(today.year - df['year'] + 0.5)


def exp_func(x, a, b, unit):
    return a * b ** (x / unit)   # b = fraction of value kept per `unit` (10.000 km or 1 year)


def fit_lin_exp(x, y, unit):
    """Linear and exponential fit; returns fit functions and % value change per `unit`."""
    slope, intercept = np.polyfit(x, y, 1)
    (a, b), _ = curve_fit(lambda xx, a, b: exp_func(xx, a, b, unit), x, y, p0=[y.max(), 0.9])
    return dict(lin=lambda xx: slope * xx + intercept,
                exp=lambda xx: exp_func(xx, a, b, unit),
                lin_pct=100 * slope / intercept * unit,   # % of fitted 0-value, per unit
                lin_eur=slope * unit,                      # € per unit (constant for a line)
                exp_pct=-(1 - b) * 100)                    # % per unit (constant for exponential;
                                                           # the € amount shrinks with the price)


rows = [
    dict(x='mileage_km', xmin=MIN_KM, unit=10000, unit_label='10.000 km',
         xlabel='Kilometerstand (km)', xfmt=lambda v, _: f'{v / 1000:.0f}k',
         hue='age_years', hue_label='Leeftijd (jaar)'),
    dict(x='age_years', xmin=MIN_AGE, unit=1, unit_label='jaar',
         xlabel='Leeftijd (jaar, sinds eerste toelating)', xfmt=lambda v, _: f'{v:.0f}',
         hue='mileage_km', hue_label='Kilometerstand (×1000 km)'),
]

cmap = 'inferno'

fig, axs = plt.subplots(2, 1, figsize=(14 * cm_to_inch, 16 * cm_to_inch))

for ax, r in zip(axs, rows):
    x_all = df[r['x']].astype(float)
    sel = df[x_all > r['xmin']]
    fit = fit_lin_exp(sel[r['x']].astype(float), sel['price'].astype(float), r['unit'])
    print(f"Fit price vs {r['x']} on {len(sel)} cars > {r['xmin']}: "
          f"linear {fit['lin_pct']:.2f}% (€{fit['lin_eur']:.0f}) / {r['unit_label']}, exponential {fit['exp_pct']:.2f}% / {r['unit_label']}")

    hue_vals = df[r['hue']] / (1000 if r['hue'] == 'mileage_km' else 1)
    sc = ax.scatter(x_all, df['price'], c=hue_vals, cmap=cmap, s=20,
                    edgecolor='black', linewidths=0.4, zorder=2)
    cb = fig.colorbar(sc, ax=ax, pad=0.02)
    cb.set_label(r['hue_label'])
    cb.outline.set_visible(False)

    x_line = np.linspace(0, x_all.max(), 200)
    ax.plot(x_line, fit['lin'](x_line), color='black', linestyle='--', linewidth=1.5, zorder=3,
            label='Lineair')
    ax.plot(x_line, fit['exp'](x_line), color='black', linestyle='-', linewidth=2, zorder=3,
            label='Exponentieel')
    ax.axvline(r['xmin'], color='#999999', linewidth=0.8, linestyle=':', zorder=1)

    # title (normal size) + fit info (smaller font) just above the plot area
    xmin_txt = f"{r['xmin']:,}".replace(',', '.') if r['unit'] > 1 else f"{r['xmin']:g}"
    eur_txt = ('−' if fit['lin_eur'] < 0 else '') + '€' + f"{abs(fit['lin_eur']):,.0f}".replace(',', '.')
    ax.set_title(f"{car_name}: waardeverlies per {r['unit_label']}", pad=22)
    ax.text(0.5, 1.015,
            f"Lineair: {fit['lin_pct']:.1f}% ({eur_txt}) per {r['unit_label']}   |   "
            f"Exponentieel: {fit['exp_pct']:.1f}% per {r['unit_label']}\n"
            f"fit op {len(sel)} auto's > {xmin_txt} {'km' if r['unit'] > 1 else 'jaar'}",
            transform=ax.transAxes, ha='center', va='bottom', fontsize=6.5, color='#444444')
    ax.set_xlabel(r['xlabel'])
    ax.set_ylabel('Prijs (€)')
    ax.xaxis.set_major_formatter(plt.FuncFormatter(r['xfmt']))
    ax.yaxis.set_major_formatter(plt.FuncFormatter(lambda y, _: f'{y:,.0f}'.replace(',', '.')))
    ax.set_xlim(left=0)
    ax.legend(frameon=False, loc='upper right')
    ax.grid(color='#dddddd', linewidth=0.5)
    ax.set_axisbelow(True)
    sn.despine(ax=ax)

plt.tight_layout()
out_base2 = out_base.replace('_mileage-vs-price', '_depreciation-fits')
fig.savefig(out_base2 + '.pdf', dpi=300, bbox_inches='tight')
fig.savefig(out_base2 + '.png', dpi=300, bbox_inches='tight')
print(f'Saved plot to {out_base2}.pdf / .png')
plt.show()
